#include <stdio.h>
/*Programa para soma de dois numeros */
int main() {
    int a, b, soma; /*declaracao de variavel*/
    printf("Digite o primeiro numero: ");
    scanf("%d", &a);
    printf("Digite o segundo numero: ");
    scanf("%d", &b);
    soma = a + b;
printf("A soma de %d e %d e: %d\n", a, b, soma);
    return 0;
}


